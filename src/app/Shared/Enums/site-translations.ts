export function translateSiteText(
  key: string,
  params?: Record<string, string | number>,
): string {
  const translation = SITE_TRANSLATIONS[key as keyof typeof SITE_TRANSLATIONS] ?? key;
  return translation.replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
    String(params?.[name] ?? ''),
  );
}

@Pipe({ name: 't', standalone: true })
export class SiteTranslationPipe implements PipeTransform {
  transform(
    key: string | null | undefined,
    params?: Record<string, string | number>,
  ): string {
    if (!key) return '';
    return translateSiteText(key, params);
  }
}
